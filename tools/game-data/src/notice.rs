//! `NOTICE.md`, next to the generated data: where they come from, and their licenses.

use std::fs;
use std::path::Path;

use crate::github::{Commit, GitHub};
use crate::{Commits, EXILED_EXCHANGE, REPOE_CODE, REPOE_DATA, Result};

/// Writes `NOTICE.md` in `output`: where the data come from (`commits`), and their licenses, that
/// of RePoE read in its code at `repoe_code_reference`.
pub fn write(
    github: &GitHub,
    output: &Path,
    commits: &Commits,
    repoe_code_reference: &str,
) -> Result<()> {
    let exiled_exchange = &commits.exiled_exchange;
    let exiled_exchange_license = github.file(EXILED_EXCHANGE, &exiled_exchange.sha, "LICENSE")?;
    let repoe_code_commit = github.commit(REPOE_CODE, repoe_code_reference)?;
    println!("RePoE code, commit {}", repoe_code_commit.sha);
    let repoe_license = github.file(REPOE_CODE, &repoe_code_commit.sha, "LICENSE.md")?;
    fs::write(
        output.join("NOTICE.md"),
        text(
            &Origin {
                commit: exiled_exchange,
                license: &exiled_exchange_license,
            },
            &Origin {
                commit: &commits.repoe_data,
                license: &repoe_license,
            },
            &commits.repoe_version,
            &repoe_code_commit.sha,
        ),
    )?;
    Ok(())
}

/// Where data come from: the commit of their repository, and their license.
struct Origin<'a> {
    commit: &'a Commit,
    license: &'a str,
}

/// The notice of the generated files; the license of `repoe_data` is that of its code, at the
/// commit `repoe_code_commit`.
fn text(
    exiled_exchange: &Origin,
    repoe_data: &Origin,
    repoe_version: &str,
    repoe_code_commit: &str,
) -> String {
    let exiled_exchange_commit = &exiled_exchange.commit.sha;
    let exiled_exchange_date = exiled_exchange.commit.date();
    let exiled_exchange_license = exiled_exchange.license.trim_end();
    let repoe_data_commit = &repoe_data.commit.sha;
    let repoe_data_date = repoe_data.commit.date();
    let repoe_license = repoe_data.license.trim_end();
    format!(
        "# Game data notice

Generated by `tools/game-data` (`cargo run -p game-data`, see `docs/game-data.md`): don't edit these files by hand, generate them again.

`stats-en.ndjson` and `stats-fr.ndjson` are the stats of [Exiled Exchange 2](https://github.com/{EXILED_EXCHANGE}) (`renderer/public/data/<language>/stats.ndjson`), commit `{exiled_exchange_commit}` of {exiled_exchange_date}, reduced to the fields the application reads and without the groups of the Sanctum. `bases-en.ndjson` and `bases-fr.ndjson` are the bases of its items (`renderer/public/data/<language>/items.ndjson`), of the same commit: the name and the category of each base of equipment, jewel, flask, charm, waystone or tablet, with the tags of the base from RePoE.

`modifiers.ndjson` holds the tiers of the prefixes and suffixes of the equipment, the jewels, the flasks, the charms, the waystones and the tablets, from the data of the [RePoE fork](https://github.com/{REPOE_DATA}) (`data/mods.json`, `data/base_items.json`, `data/stat_translations/stat_descriptions.json` and `data/stat_translations/tablet_stat_descriptions.json`), commit `{repoe_data_commit}` of {repoe_data_date}, export of the version {repoe_version} of the game, their lines written as the templates of Exiled Exchange 2. The bases of the modifiers only an essence adds, which RePoE doesn't give, are those of [Craft of Exile](https://www.craftofexile.com), checked on the trade site.

Their texts, ids and values come from the files of Path of Exile 2 and belong to Grinding Gear Games; they are used here in a free, non-commercial tool. The files of Exiled Exchange 2 are under the MIT license, whose notice follows:

```text
{exiled_exchange_license}
```

The code of the RePoE fork ([{REPOE_CODE}](https://github.com/{REPOE_CODE}), commit `{repoe_code_commit}`), which exports these data, is under the MIT license, whose notice follows:

```text
{repoe_license}
```

This product isn't affiliated with or endorsed by Grinding Gear Games in any way.
"
    )
}
