//! `NOTICE.md`, next to the generated data: where they come from, and their licenses.

use std::fs;
use std::path::Path;

use crate::github::{Commit, GitHub};
use crate::{EXILED_EXCHANGE, REPOE_CODE, REPOE_DATA, Result, Sources};

/// Writes `NOTICE.md` in `output`: where the data come from (`sources`), and their licenses, that
/// of RePoE read in its code at `repoe_code_reference`.
pub(crate) fn write(
    github: &GitHub,
    output: &Path,
    sources: &Sources,
    repoe_code_reference: &str,
) -> Result<()> {
    let exiled_exchange = &sources.exiled_exchange;
    let license = github.file(EXILED_EXCHANGE, &exiled_exchange.sha, "LICENSE")?;
    let repoe_code = github.commit(REPOE_CODE, repoe_code_reference)?;
    println!("RePoE code, commit {}", repoe_code.sha);
    let repoe_license = github.file(REPOE_CODE, &repoe_code.sha, "LICENSE.md")?;
    fs::write(
        output.join("NOTICE.md"),
        text(
            &Origin {
                commit: exiled_exchange,
                license: &license,
            },
            &Origin {
                commit: &sources.repoe_data,
                license: &repoe_license,
            },
            &sources.repoe_version,
            &repoe_code.sha,
        ),
    )?;
    Ok(())
}

/// Where data come from: the commit of their repository, and their license.
struct Origin<'a> {
    commit: &'a Commit,
    license: &'a str,
}

/// The notice of the generated files; the license of `repoe` is that of its code, at the commit
/// `repoe_code`.
fn text(exiled_exchange: &Origin, repoe: &Origin, repoe_version: &str, repoe_code: &str) -> String {
    format!(
        "# Game data notice

Generated by `tools/game-data` (`cargo run -p game-data`, see `docs/game-data.md`): don't edit these files by hand, generate them again.

`stats-en.ndjson` and `stats-fr.ndjson` are the stats of [Exiled Exchange 2](https://github.com/{EXILED_EXCHANGE}) (`renderer/public/data/<language>/stats.ndjson`), commit `{}` of {}, reduced to the fields the application reads and without the groups of the Sanctum. `bases-en.ndjson` and `bases-fr.ndjson` are the bases of its items (`renderer/public/data/<language>/items.ndjson`), of the same commit: the name and the category of each base of equipment, jewel, flask, charm, waystone or tablet, with the tags of the base from RePoE.

`modifiers.ndjson` holds the tiers of the prefixes and suffixes of the equipment, the jewels, the flasks, the charms, the waystones and the tablets, from the data of the [RePoE fork](https://github.com/{REPOE_DATA}) (`data/mods.json`, `data/base_items.json`, `data/stat_translations/stat_descriptions.json` and `data/stat_translations/tablet_stat_descriptions.json`), commit `{}` of {}, export of the version {repoe_version} of the game, their lines written as the templates of Exiled Exchange 2. The bases of the modifiers only an essence adds, which RePoE doesn't give, are those of [Craft of Exile](https://www.craftofexile.com), checked on the trade site.

Their texts, ids and values come from the files of Path of Exile 2 and belong to Grinding Gear Games; they are used here in a free, non-commercial tool. The files of Exiled Exchange 2 are under the MIT license, whose notice follows:

```text
{}
```

The code of the RePoE fork ([{REPOE_CODE}](https://github.com/{REPOE_CODE}), commit `{repoe_code}`), which exports these data, is under the MIT license, whose notice follows:

```text
{}
```

This product isn't affiliated with or endorsed by Grinding Gear Games in any way.
",
        exiled_exchange.commit.sha,
        exiled_exchange.commit.date(),
        repoe.commit.sha,
        repoe.commit.date(),
        exiled_exchange.license.trim_end(),
        repoe.license.trim_end(),
    )
}
